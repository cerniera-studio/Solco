"""Solco's launcher icon, drawn once and written out as the Android layers and an SVG preview.

The mark is a glyph in the family's language (see Cielo and Fold Motion): bold strokes an icon
pack can set on its own glass, everything inside the adaptive icon's safe zone (radius 33 round
the centre of the 108 canvas).

    grooves     three furrows of grain on rings centred on the hinge (off the left edge of the
                mark), the grains closer together and brighter outwards. Rows of grain, not
                lines: solid arcs from a point read as a Wi-Fi or speaker symbol.
    the sun     capping the outer furrow, high, as at midday
    (cut: three grains thrown past the outer furrow; they crowded its end, and the furrows are
    already grain)

Run:  python3 tools/icon.py            (writes the drawables)
      python3 tools/icon.py --preview  (also writes tools/icon-preview.svg)
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"

HX, HY = 24.0, 54.0               # the hinge, the rings' centre (nothing is drawn there)
GROOVES = [(18, 62, 0.55, 5.2), (28, 56, 0.78, 4.6), (38, 50, 1.0, 4.2)]  # radius, half-sweep, alpha, spacing
DOT = 1.35                        # a grain in a furrow
SUN_R, SUN_AT = 7.0, -30.0        # disc radius, its angle on the outer groove
GRAIN = []  # radius, angle, alpha
GRAIN_R = 1.8

IVORY, CHAMPAGNE = "F6F1E6", "D9BB86"


def pt(r, deg):
    a = math.radians(deg)
    return HX + r * math.cos(a), HY + r * math.sin(a)


def furrow(r, half, spacing):
    """Grain centres along one furrow, evenly spaced, leaving room for the sun on the outer one."""
    n = max(2, round(math.radians(2 * half) * r / spacing))
    angles = [-half + 2 * half * i / n for i in range(n + 1)]
    if r == GROOVES[-1][0]:  # the outer furrow runs up to the sun and stops: the sun caps it
        angles = [a for a in angles if a > SUN_AT and math.hypot(*(p - q for p, q in zip(pt(r, a), SUN))) > SUN_R + 2.2]
    pts = [pt(r, a) for a in angles]
    return pts


def circle(cx, cy, r):
    return f"M{cx:.2f},{cy:.2f} m-{r},0 a{r},{r} 0,1 1 {2*r},0 a{r},{r} 0,1 1 -{2*r},0"


SUN = pt(GROOVES[-1][0], SUN_AT)


def check_safe_zone():
    worst = 0.0
    for r, half, _, sp in GROOVES:
        for x, y in furrow(r, half, sp):
            worst = max(worst, math.hypot(x - 54, y - 54) + DOT)
    worst = max(worst, math.hypot(SUN[0] - 54, SUN[1] - 54) + SUN_R)
    for r, d, _ in GRAIN:
        x, y = pt(r, d)
        worst = max(worst, math.hypot(x - 54, y - 54) + GRAIN_R)
    assert worst <= 33, f"mark reaches {worst:.1f} from the centre; the safe zone is 33"
    return worst


HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n')
AAPT = ' xmlns:aapt="http://schemas.android.com/aapt"'


def fill(d, color, alpha=1.0):
    return f'    <path android:fillColor="#{round(alpha * 255):02X}{color}" android:pathData="{d}" />\n'


def foreground():
    sx, sy = SUN
    out = HEAD.format(ns=AAPT)
    out += "    <!-- Solco: grooves round the hinge, the sun riding the outer one, grain thrown by the swing.\n"
    out += "         Generated by tools/icon.py. Lit from the upper left like the rest of the family. -->\n"
    out += f'    <path android:pathData="{circle(sx, sy, 16)}">\n'
    out += '        <aapt:attr name="android:fillColor">\n'
    out += (f'            <gradient android:type="radial" android:centerX="{sx:.2f}" android:centerY="{sy:.2f}"'
            ' android:gradientRadius="16"\n'
            '                android:startColor="#33D9BB86" android:endColor="#00D9BB86" />\n')
    out += "        </aapt:attr>\n    </path>\n"
    for r, half, a, sp in GROOVES:
        out += fill("".join(circle(x, y, DOT) for x, y in furrow(r, half, sp)), IVORY, a)
    for r, d, a in GRAIN:
        out += fill(circle(*pt(r, d), GRAIN_R), CHAMPAGNE, a)
    out += f'    <path android:pathData="{circle(sx, sy, SUN_R)}">\n'
    out += '        <aapt:attr name="android:fillColor">\n'
    out += (f'            <gradient android:type="linear" android:startX="{sx-5:.2f}" android:startY="{sy-5:.2f}"'
            f' android:endX="{sx+5:.2f}" android:endY="{sy+5:.2f}"\n'
            '                android:startColor="#FFEBD3A6" android:endColor="#FFB8955A" />\n')
    out += "        </aapt:attr>\n    </path>\n</vector>\n"
    return out


def monochrome():
    sx, sy = SUN
    out = HEAD.format(ns="")
    out += "    <!-- One UI themed icons and icon packs. Generated by tools/icon.py. -->\n"
    for r, half, _, sp in GROOVES:
        out += fill("".join(circle(x, y, DOT + 0.2) for x, y in furrow(r, half, sp)), "FFFFFF")
    for r, d, _ in GRAIN:
        out += fill(circle(*pt(r, d), GRAIN_R), "FFFFFF")
    out += fill(circle(sx, sy, SUN_R), "FFFFFF")
    return out + "</vector>\n"


BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Smoked green-black, lit from the upper left (the family's ground, as Cielo's) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="30" android:centerY="26" android:gradientRadius="110"
                android:startColor="#FF1B2420" android:endColor="#FF0E1311" />
        </aapt:attr>
    </path>
</vector>
"""


def preview():
    """Old and new side by side: in full colour, and as an icon pack sets the monochrome glyph on its glass."""
    sx, sy = SUN

    def colour(ox):
        g = f'<g transform="translate({ox},0)" clip-path="url(#sq)">'
        g += '<rect width="108" height="108" fill="url(#bg)"/>'
        g += f'<circle cx="{sx:.2f}" cy="{sy:.2f}" r="16" fill="url(#halo)"/>'
        for r, half, a, sp in GROOVES:
            for x, y in furrow(r, half, sp):
                g += f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{DOT}" fill="#{IVORY}" fill-opacity="{a}"/>'
        for r, d, a in GRAIN:
            x, y = pt(r, d)
            g += f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{GRAIN_R}" fill="#{CHAMPAGNE}" fill-opacity="{a}"/>'
        g += f'<circle cx="{sx:.2f}" cy="{sy:.2f}" r="{SUN_R}" fill="url(#sun)"/></g>'
        return g

    def glass(ox):
        g = f'<g transform="translate({ox},0)" clip-path="url(#sq)">'
        g += '<rect width="108" height="108" fill="url(#glass)"/><rect width="10" height="108" fill="url(#bevel)"/>'
        for r, half, _, sp in GROOVES:
            for x, y in furrow(r, half, sp):
                g += f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{DOT + 0.2}" fill="#111"/>'
        for r, d, _ in GRAIN:
            x, y = pt(r, d)
            g += f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{GRAIN_R}" fill="#111"/>'
        g += f'<circle cx="{sx:.2f}" cy="{sy:.2f}" r="{SUN_R}" fill="#111"/></g>'
        return g

    defs = f"""<defs>
<clipPath id="sq"><rect width="108" height="108" rx="20"/></clipPath>
<radialGradient id="bg" cx="30" cy="26" r="110" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#1B2420"/><stop offset="1" stop-color="#0E1311"/></radialGradient>
<radialGradient id="halo" cx="{sx:.2f}" cy="{sy:.2f}" r="16" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#D9BB86" stop-opacity=".2"/><stop offset="1" stop-color="#D9BB86" stop-opacity="0"/></radialGradient>
<linearGradient id="sun" x1="{sx-5:.2f}" y1="{sy-5:.2f}" x2="{sx+5:.2f}" y2="{sy+5:.2f}" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#EBD3A6"/><stop offset="1" stop-color="#B8955A"/></linearGradient>
<linearGradient id="glass" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#8E9C9A"/><stop offset=".5" stop-color="#7C8C8A"/><stop offset="1" stop-color="#899795"/></linearGradient>
<linearGradient id="bevel" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#2A302F"/><stop offset=".5" stop-color="#E8EEED"/><stop offset="1" stop-color="#8E9C9A" stop-opacity="0"/></linearGradient>
</defs>"""
    label = 'font-family="sans-serif" font-size="7" fill="#C9C4B8" text-anchor="middle"'
    body = colour(10) + glass(138)
    body += f'<text x="64" y="124" {label}>Full colour</text><text x="192" y="124" {label}>As your pack sets it</text>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 134" width="1024" height="536">'
            f'<rect width="256" height="134" fill="#2B2D28"/>{defs}{body}</svg>\n')


if __name__ == "__main__":
    reach = check_safe_zone()
    (RES / "ic_launcher_foreground.xml").write_text(foreground())
    (RES / "ic_launcher_monochrome.xml").write_text(monochrome())
    (RES / "ic_launcher_background.xml").write_text(BACKGROUND)
    print(f"icon written; mark reaches {reach:.1f} of 33 from the centre")
    if "--preview" in sys.argv:
        (ROOT / "tools/icon-preview.svg").write_text(preview())
        print("preview written")
